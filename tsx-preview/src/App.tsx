// ─── GATE ────────────────────────────────────────────────────────
function canProceed(step, form) {
  const audienceAllowed = form.industry !== "food" || form.audience === "public";
  switch (step) {
    case 1: return !!(form.industry && form.product);
    case 2: return !!(form.audience && audienceAllowed && form.problems.length >= 1);
    case 3: return !!(form.scene && form.gender && form.clothing && form.colorTheme && form.pose);
    case 4: return !!(form.duration && form.aspectRatio && form.music);
    case 5: return !!(form.broll && form.subtitle && form.cta);
    case 6: return !!(form.brandName.trim() && form.productDesc.trim() && hasRoiValue(form) && form.logo && form.productImages.length >= 1);
    default: return false;
  }
}

