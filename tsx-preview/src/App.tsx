const ROI_BY_PRODUCT_PROBLEM = Object.fromEntries(
  Object.entries(PROBLEMS).map(([productId, problems]) => {
    const industry = getIndustry(productId) || "it";
    const productName = getProductName(industry, productId);
    return [
      productId,
      Object.fromEntries(problems.map(problem => [problem, makeProblemRois(productName, industry, problem)])),
    ];
  })
);
function getRoiSuggestions(form) {
  if (!form.product || !form.problems?.length) return [];
  const productRois = ROI_BY_PRODUCT_PROBLEM[form.product] || {};
  const industry = form.industry || getIndustry(form.product) || "it";
  const productName = getProductName(industry, form.product);
  const onePerProblem = form.problems.length > 2;
  return form.problems.flatMap(problem => {
    const suggestions = productRois[problem] || makeProblemRois(productName, industry, problem);
    return onePerProblem ? suggestions.slice(0, 1) : suggestions;
  });
}
function activeRoiSuggestions(form) {
  const dismissed = form.roiDismissed || [];
  return getRoiSuggestions(form).filter(text => !dismissed.includes(text));
}
function hasRoiValue(form) {
  return !!form.roi.trim() || activeRoiSuggestions(form).length > 0;
}
