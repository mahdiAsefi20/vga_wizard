export default function App() {
  useEffect(() => {
    const l = document.createElement("link");
    l.rel = "stylesheet";
    l.href = "https://fonts.googleapis.com/css2?family=Vazirmatn:wght@300;400;500;600;700&display=swap";
    document.head.appendChild(l);
    return () => {
      if (l.parentNode) l.parentNode.removeChild(l);
    };
  }, []);

  const [step, setStep]   = useState(1);
  const [done, setDone]   = useState(false);
  const [form, setForm]   = useState(DEFAULT);
  const topRef            = useRef();

  const allIssues = useMemo(() => runValidation(form), [form]);
  const ok        = canProceed(step, form);

  const scrollTop = () => {
    topRef.current?.scrollIntoView({ behavior: "instant", block: "start" });
    window.scrollTo(0, 0);
  };

  const goNext = () => {
    if (!ok) return;
    if (step === 6) { setDone(true); }
    else setStep(s => s + 1);
    scrollTop();
  };
  const goPrev = () => { setStep(s => s - 1); scrollTop(); };
  const reset  = () => { setDone(false); setStep(1); setForm(DEFAULT); };

  const STEPS = [
    <Step1 form={form} setForm={setForm} />,
    <Step2 form={form} setForm={setForm} />,
    <Step3 form={form} setForm={setForm} allIssues={allIssues} />,
    <Step4 form={form} setForm={setForm} allIssues={allIssues} />,
    <Step5 form={form} setForm={setForm} allIssues={allIssues} />,
    <Step6 form={form} setForm={setForm} />,
  ];

  return (
    <div ref={topRef} dir="rtl" style={{ fontFamily: "'Vazirmatn',sans-serif" }} className="min-h-screen bg-slate-50 py-6 px-4">
      <div className="max-w-2xl mx-auto">
        <div className="text-center mb-6">
          <div className="inline-flex items-center gap-1.5 bg-blue-600 text-white text-xs font-semibold px-3 py-1.5 rounded-full mb-2">
            <Sparkles size={10} />ساخت ویدیو با هوش مصنوعی
          </div>
          <h1 className="text-xl font-bold text-gray-900">ویدیوساز هوشمند</h1>
        </div>

        {!done && <Progress current={step} allIssues={allIssues} />}

        <div className="bg-white rounded-3xl shadow-sm border border-gray-100">
          <div className="p-5 sm:p-7">
            {done ? <Done form={form} onReset={reset} /> : (
              <>
                {STEPS[step - 1]}
                <div className="flex items-center justify-between mt-7 pt-5 border-t border-gray-100">
                  <div>
                    {step > 1 && (
                      <button type="button" onClick={goPrev}
                        className="flex items-center gap-1 text-gray-500 hover:text-gray-700 text-sm font-medium px-3 py-2.5 rounded-xl hover:bg-gray-100 transition-colors">
                        مرحله قبل<ChevronRight size={16} />
                      </button>
                    )}
                  </div>
                  <button type="button" onClick={goNext} disabled={!ok}
                    className={`flex items-center gap-1.5 text-sm font-bold px-6 py-2.5 rounded-xl transition-all
                      ${ok ? "bg-blue-600 text-white hover:bg-blue-700 shadow-sm" : "bg-gray-100 text-gray-400 cursor-not-allowed"}`}>
                    <ChevronLeft size={16} />
                    {step === 6 ? "ساخت ویدیو" : "مرحله بعد"}
                  </button>
                </div>
              </>
            )}
          </div>
        </div>
        {!done && <p className="text-center text-xs text-gray-400 mt-3">مرحله {step} از {STEP_META.length}</p>}
      </div>
    </div>
  );
}
