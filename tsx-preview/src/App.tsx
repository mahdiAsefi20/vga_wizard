function runValidation(form) {
  return RULES.filter(r => r.match(form));
}
function activeRulesForFields(form, allIssues, keys) {
  return allIssues.filter(i =>
    i.fields.some(f => keys.includes(f)) &&
    i.fields.every(f => form[f] != null && form[f] !== "")
  );
}
function previewSev(form, key, val) {
  const h = { ...form, [key]: val };
  const hits = RULES.filter(r => r.fields.includes(key) && r.match(h));
  if (hits.some(r => r.severity === "critical")) return "critical";
  if (hits.length) return "warning";
  return null;
}
function isCriticalChoice(form, key, val) {
  return previewSev(form, key, val) === "critical";
}
function hasIssue(form, key, val, severity) {
  const next = { ...form, [key]: val };
  return RULES.some(rule =>
    rule.severity === severity &&
    rule.fields.includes(key) &&
    rule.match(next)
  );
}
function safeSuggestion(form, key, value) {
  return !hasIssue(form, key, value, "warning") && !hasIssue(form, key, value, "critical");
}
function isSuggested(form, key, value, suggestion) {
  return suggestion === value && form[key] !== value && safeSuggestion(form, key, value);
}

