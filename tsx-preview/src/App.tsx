function hasAny(text, words) {
  return words.some(word => text.includes(word));
}
function roiTheme(problem) {
  if (hasAny(problem, ["باتری", "شارژ", "برق", "مصرف انرژی", "مصرف برق"])) return "power";
  if (hasAny(problem, ["کند", "سرعت", "تاخیر", "تأخیر", "عملکرد", "پردازش", "قطعی", "از کار افتادن"])) return "speed";
  if (hasAny(problem, ["داغ", "گرما", "خنک", "حرارت"])) return "heat";
  if (hasAny(problem, ["قیمت", "هزینه", "گران", "تعمیر", "نگهداری", "لوازم مصرفی"])) return "cost";
  if (hasAny(problem, ["امنیت", "هک", "نفوذ", "داده", "اطلاعات", "نشت"])) return "security";
  if (hasAny(problem, ["ناسازگاری", "سازگاری", "اتصال", "درایور", "شبکه", "وای‌فای", "آنتن"])) return "compatibility";
  if (hasAny(problem, ["کیفیت", "دقت", "تصویر", "رنگ", "صدا", "نویز", "طعم", "بو", "ظاهر"])) return "quality";
  if (hasAny(problem, ["رابط", "پیچیده", "سخت", "آموزش", "تنظیم", "نصب", "راه‌اندازی"])) return "ease";
  if (hasAny(problem, ["بسته‌بندی", "نشتی", "نفوذ هوا", "شکستن", "حمل و نقل", "ظرف"])) return "packaging";
  if (hasAny(problem, ["انقضا", "ماندگاری", "فساد", "کپک", "تازگی", "رطوبت"])) return "freshness";
  if (hasAny(problem, ["اعتماد", "برند", "فروش", "رقابت", "جذابیت"])) return "trust";
  if (hasAny(problem, ["وزن", "حجم", "فضای", "حمل", "جا"])) return "size";
  return "general";
}
